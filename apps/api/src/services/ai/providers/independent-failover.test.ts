import { describe, it, expect, vi, beforeAll, afterAll, beforeEach } from 'vitest';
import http from 'node:http';
import { AddressInfo } from 'node:net';
import { ResilientFallbackProvider } from './resilient-fallback.provider.js';
import { OpenAICompatibleProvider } from './openai-compatible.provider.js';
import { CircuitBreaker } from '../circuit-breaker.js';
import {
  type IAIProvider,
  AITemporaryUnavailableError,
  AIExplanationRequest,
} from '../provider.interface.js';
import { AIProviderFactory } from '../provider.factory.js';

describe('Independent AI Provider Failover (Deterministic)', () => {
  let mockServer: http.Server;
  let mockServerUrl: string;
  let mockServerPort: number;
  let requestHandler: (req: http.IncomingMessage, res: http.ServerResponse) => void;
  let receivedRequests: Array<{
    url: string;
    method: string;
    headers: http.IncomingHttpHeaders;
    body: any;
  }> = [];

  const sampleExplanation = {
    summary: 'Architecture summary from independent fallback provider',
    explanation: 'Detailed structural walkthrough generated by independent fallback model',
    keyTakeaways: [
      'Layered modular architecture with clear boundary isolation',
      'Independent fallback provider maintains system availability during primary outage',
    ],
    evidence: [
      {
        type: 'file',
        label: 'src/server.ts',
        reference: 'src/server.ts',
        description: 'HTTP API server entry point',
      },
    ],
  };

  beforeAll(async () => {
    mockServer = http.createServer((req, res) => {
      let data = '';
      req.on('data', (chunk) => {
        data += chunk;
      });
      req.on('end', () => {
        let parsedBody: any = null;
        try {
          if (data) parsedBody = JSON.parse(data);
        } catch {
          parsedBody = data;
        }
        receivedRequests.push({
          url: req.url || '',
          method: req.method || '',
          headers: req.headers,
          body: parsedBody,
        });

        if (requestHandler) {
          requestHandler(req, res);
        } else {
          res.writeHead(404, { 'Content-Type': 'application/json' });
          res.end(JSON.stringify({ error: 'No handler configured' }));
        }
      });
    });

    await new Promise<void>((resolve) => {
      mockServer.listen(0, '127.0.0.1', () => {
        const addr = mockServer.address() as AddressInfo;
        mockServerPort = addr.port;
        mockServerUrl = `http://127.0.0.1:${mockServerPort}/v1`;
        resolve();
      });
    });
  });

  afterAll(async () => {
    await new Promise<void>((resolve) => {
      mockServer.close(() => resolve());
    });
  });

  beforeEach(() => {
    receivedRequests = [];
    vi.restoreAllMocks();
  });

  const baseRequest: AIExplanationRequest = {
    topic: 'overview',
    context: 'Deterministic repository facts: Fastify backend with TypeScript',
    repoName: 'test-org/test-repo',
  };

  /**
   * 1. Gemini returns HTTP 503 and independent fallback succeeds
   */
  it('falls back to local OpenAI-compatible endpoint when primary Gemini fails with 503', async () => {
    // Primary Gemini provider stubs 503 Unavailable
    const primaryGemini: IAIProvider = {
      name: 'gemini',
      model: 'gemini-3.8-flash',
      explain: vi.fn().mockRejectedValue(new AITemporaryUnavailableError('Gemini 503 Service Unavailable')),
    };

    // Configure mock server to return valid OpenAI chat completion
    requestHandler = (_req, res) => {
      res.writeHead(200, { 'Content-Type': 'application/json' });
      res.end(
        JSON.stringify({
          id: 'chatcmpl-mock-123',
          object: 'chat.completion',
          choices: [
            {
              index: 0,
              message: {
                role: 'assistant',
                content: JSON.stringify(sampleExplanation),
              },
              finish_reason: 'stop',
            },
          ],
          usage: { prompt_tokens: 50, completion_tokens: 100, total_tokens: 150 },
        })
      );
    };

    const fallbackOpenAI = new OpenAICompatibleProvider({
      apiKey: 'test-fallback-secret-key',
      baseUrl: mockServerUrl,
      model: 'test-fallback-model',
      maxRetries: 0,
    });

    const primaryBreaker = new CircuitBreaker({ name: 'gemini', failureThreshold: 3 });
    const fallbackBreaker = new CircuitBreaker({ name: 'openai-compatible', failureThreshold: 3 });

    const resilient = new ResilientFallbackProvider([
      { provider: primaryGemini, breaker: primaryBreaker },
      { provider: fallbackOpenAI, breaker: fallbackBreaker },
    ]);

    const result = await resilient.explain(baseRequest);

    // Verify fallback result structure
    expect(result.summary).toBe(sampleExplanation.summary);
    expect(result.explanation).toBe(sampleExplanation.explanation);
    expect(result.keyTakeaways).toHaveLength(2);
    expect(result.evidence).toHaveLength(1);
    expect(result.provider).toBe('openai-compatible');
    expect(result.model).toBe('test-fallback-model');

    // Verify invocation sequence
    expect(primaryGemini.explain).toHaveBeenCalledTimes(1);
    expect(primaryBreaker.getStatus().consecutiveFailures).toBe(1);
    expect(fallbackBreaker.getStatus().consecutiveFailures).toBe(0);

    // Verify HTTP wire communication with mock server
    expect(receivedRequests).toHaveLength(1);
    const req = receivedRequests[0];
    expect(req.url).toBe('/v1/chat/completions');
    expect(req.method).toBe('POST');
    expect(req.headers['authorization']).toBe('Bearer test-fallback-secret-key');
    expect(req.headers['content-type']).toBe('application/json');
    expect(req.body.model).toBe('test-fallback-model');
    expect(req.body.messages).toBeDefined();
    expect(req.body.messages[1].content).toBe(baseRequest.context);
  });

  /**
   * 2. Both providers fail and ArchLens returns a sanitized, actionable error
   */
  it('returns a sanitized actionable AITemporaryUnavailableError when both providers fail', async () => {
    const primaryGemini: IAIProvider = {
      name: 'gemini',
      model: 'gemini-3.8-flash',
      explain: vi.fn().mockRejectedValue(new AITemporaryUnavailableError('Gemini backend overloaded (503)')),
    };

    requestHandler = (_req, res) => {
      res.writeHead(503, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ error: { message: 'Upstream OpenAI server overloaded', code: 503 } }));
    };

    const fallbackOpenAI = new OpenAICompatibleProvider({
      apiKey: 'test-fallback-key',
      baseUrl: mockServerUrl,
      model: 'test-fallback-model',
      maxRetries: 0,
    });

    const resilient = new ResilientFallbackProvider([
      { provider: primaryGemini, breaker: new CircuitBreaker({ name: 'gemini' }) },
      { provider: fallbackOpenAI, breaker: new CircuitBreaker({ name: 'openai-compatible' }) },
    ]);

    await expect(resilient.explain(baseRequest)).rejects.toThrow(AITemporaryUnavailableError);
    await expect(resilient.explain(baseRequest)).rejects.toThrow(/All configured AI providers are temporarily unavailable/);

    expect(primaryGemini.explain).toHaveBeenCalled();
    expect(receivedRequests.length).toBeGreaterThanOrEqual(1);
  });

  /**
   * 3. An open circuit avoids repeatedly calling an unhealthy provider
   */
  it('trips primary circuit breaker to OPEN after 3 failures and skips primary on 4th call', async () => {
    const primaryGemini: IAIProvider = {
      name: 'gemini',
      model: 'gemini-3.8-flash',
      explain: vi.fn().mockRejectedValue(new AITemporaryUnavailableError('503 Service Unavailable')),
    };

    requestHandler = (_req, res) => {
      res.writeHead(200, { 'Content-Type': 'application/json' });
      res.end(
        JSON.stringify({
          choices: [{ message: { content: JSON.stringify(sampleExplanation) } }],
        })
      );
    };

    const fallbackOpenAI = new OpenAICompatibleProvider({
      apiKey: 'test-fallback-key',
      baseUrl: mockServerUrl,
      model: 'test-fallback-model',
      maxRetries: 0,
    });

    const primaryBreaker = new CircuitBreaker({ name: 'gemini', failureThreshold: 3, cooldownMs: 60_000 });
    const fallbackBreaker = new CircuitBreaker({ name: 'openai-compatible' });

    const resilient = new ResilientFallbackProvider([
      { provider: primaryGemini, breaker: primaryBreaker },
      { provider: fallbackOpenAI, breaker: fallbackBreaker },
    ]);

    // 1st request -> Gemini fails (1/3) -> fallback succeeds
    await resilient.explain(baseRequest);
    expect(primaryBreaker.getState()).toBe('CLOSED');
    expect(primaryBreaker.getStatus().consecutiveFailures).toBe(1);

    // 2nd request -> Gemini fails (2/3) -> fallback succeeds
    await resilient.explain(baseRequest);
    expect(primaryBreaker.getState()).toBe('CLOSED');
    expect(primaryBreaker.getStatus().consecutiveFailures).toBe(2);

    // 3rd request -> Gemini fails (3/3) -> trips to OPEN
    await resilient.explain(baseRequest);
    expect(primaryBreaker.getState()).toBe('OPEN');
    expect(primaryBreaker.isOpen()).toBe(true);

    // Reset spy call count before 4th call
    (primaryGemini.explain as any).mockClear();
    receivedRequests = [];

    // 4th request -> Gemini circuit is OPEN, so Gemini explain() is NEVER called!
    const fourthResult = await resilient.explain(baseRequest);
    expect(fourthResult.provider).toBe('openai-compatible');
    expect(primaryGemini.explain).not.toHaveBeenCalled(); // Skipped without network call!
    expect(receivedRequests).toHaveLength(1); // Directly went to fallback!
  });

  /**
   * 4. The circuit permits a recovery attempt after its cooldown (deterministic clock)
   */
  it('transitions to HALF_OPEN after cooldown and resets to CLOSED upon successful probe', async () => {
    let simulatedNow = 100_000;
    const cooldownMs = 30_000;

    const primaryGemini: IAIProvider = {
      name: 'gemini',
      model: 'gemini-3.8-flash',
      explain: vi.fn(),
    };

    requestHandler = (_req, res) => {
      res.writeHead(200, { 'Content-Type': 'application/json' });
      res.end(
        JSON.stringify({
          choices: [{ message: { content: JSON.stringify(sampleExplanation) } }],
        })
      );
    };

    const fallbackOpenAI = new OpenAICompatibleProvider({
      apiKey: 'test-fallback-key',
      baseUrl: mockServerUrl,
      model: 'test-fallback-model',
      maxRetries: 0,
    });

    const primaryBreaker = new CircuitBreaker({
      name: 'gemini',
      failureThreshold: 2,
      cooldownMs,
      nowFn: () => simulatedNow,
    });

    const resilient = new ResilientFallbackProvider([
      { provider: primaryGemini, breaker: primaryBreaker },
      { provider: fallbackOpenAI, breaker: new CircuitBreaker({ name: 'fallback' }) },
    ]);

    // Trip the breaker with 2 failures
    (primaryGemini.explain as any).mockRejectedValue(new AITemporaryUnavailableError('503'));
    await resilient.explain(baseRequest);
    await resilient.explain(baseRequest);
    expect(primaryBreaker.getState()).toBe('OPEN');

    // Time advances, but still within cooldown
    simulatedNow += 15_000;
    expect(primaryBreaker.getState()).toBe('OPEN');

    // Time advances past cooldown -> state transitions to HALF_OPEN
    simulatedNow += 16_000; // total 31s > 30s
    expect(primaryBreaker.getState()).toBe('HALF_OPEN');

    // Primary Gemini recovers and returns successful result
    (primaryGemini.explain as any).mockResolvedValue({
      summary: 'Primary Gemini recovered summary',
      explanation: 'Explanation',
      keyTakeaways: [],
      evidence: [],
      provider: 'gemini',
      model: 'gemini-3.8-flash',
    });

    (primaryGemini.explain as any).mockClear();
    receivedRequests = [];

    // Probe request is allowed to primary
    const probeResult = await resilient.explain(baseRequest);
    expect(probeResult.provider).toBe('gemini');
    expect(probeResult.summary).toBe('Primary Gemini recovered summary');
    expect(primaryGemini.explain).toHaveBeenCalledTimes(1);

    // Primary circuit breaker is now fully CLOSED
    expect(primaryBreaker.getState()).toBe('CLOSED');
    expect(primaryBreaker.getStatus().consecutiveFailures).toBe(0);
    // Fallback was not called during successful recovery
    expect(receivedRequests).toHaveLength(0);
  });

  /**
   * 5. Missing fallback configuration is handled explicitly
   */
  it('handles missing fallback configuration explicitly without unhandled errors', async () => {
    // When only Gemini key is provided, factory returns chain with only Gemini
    const providerWithOnlyGemini = AIProviderFactory.create({
      providerType: 'gemini',
      geminiApiKey: 'test-gemini-key',
      disableCircuitBreaker: true,
    });
    expect(providerWithOnlyGemini.name).toBe('gemini');

    // When Gemini fails and there is no fallback configured in ResilientFallbackProvider
    const solePrimary: IAIProvider = {
      name: 'gemini',
      model: 'gemini-3.8-flash',
      explain: vi.fn().mockRejectedValue(new AITemporaryUnavailableError('503 Outage')),
    };

    const singleEntryResilient = new ResilientFallbackProvider([
      { provider: solePrimary, breaker: new CircuitBreaker({ name: 'gemini' }) },
    ]);

    await expect(singleEntryResilient.explain(baseRequest)).rejects.toThrow(AITemporaryUnavailableError);
    await expect(singleEntryResilient.explain(baseRequest)).rejects.toThrow(
      /All configured AI providers are temporarily unavailable: 503 Outage/
    );

    // Empty entries array is rejected at construction
    expect(() => new ResilientFallbackProvider([])).toThrow(
      'ResilientFallbackProvider requires at least one provider entry.'
    );
  });

  /**
   * 6. Provider errors, timeouts and retries do not leak secrets or duplicate unintended work
   */
  it('redacts sensitive API keys from error messages during fallback failures', async () => {
    const sensitiveKey = 'sk-proj-SUPER_SECRET_KEY_987654321';

    requestHandler = (_req, res) => {
      res.writeHead(401, { 'Content-Type': 'application/json' });
      res.end(`Unauthorized access with provided token ${sensitiveKey}`);
    };

    const provider = new OpenAICompatibleProvider({
      apiKey: sensitiveKey,
      baseUrl: mockServerUrl,
      maxRetries: 0,
    });

    try {
      await provider.explain(baseRequest);
      expect.fail('Expected provider to throw on 401');
    } catch (err: any) {
      expect(err.message).not.toContain(sensitiveKey);
      expect(err.message).toContain('[REDACTED]');
    }
  });

  it('aborts immediately and terminates cleanly when AbortSignal is triggered', async () => {
    const primaryGemini: IAIProvider = {
      name: 'gemini',
      model: 'gemini-3.8-flash',
      explain: vi.fn(),
    };

    const fallbackOpenAI = new OpenAICompatibleProvider({
      apiKey: 'test-fallback-key',
      baseUrl: mockServerUrl,
    });

    const resilient = new ResilientFallbackProvider([
      { provider: primaryGemini, breaker: new CircuitBreaker({ name: 'gemini' }) },
      { provider: fallbackOpenAI, breaker: new CircuitBreaker({ name: 'openai-compatible' }) },
    ]);

    const abortController = new AbortController();
    abortController.abort();

    await expect(
      resilient.explain({
        ...baseRequest,
        signal: abortController.signal,
      })
    ).rejects.toThrow(/aborted/i);

    expect(primaryGemini.explain).not.toHaveBeenCalled();
    expect(receivedRequests).toHaveLength(0);
  });

  it('enforces request timeout when fallback server hangs', async () => {
    // Mock server intentionally never responds
    requestHandler = (_req, _res) => {
      // Intentionally do nothing to induce timeout
    };

    const fallbackWithTimeout = new OpenAICompatibleProvider({
      apiKey: 'test-key',
      baseUrl: mockServerUrl,
      perAttemptTimeoutMs: 100, // Short timeout
      maxRetries: 0,
    });

    await expect(fallbackWithTimeout.explain(baseRequest)).rejects.toThrow(/timed out/i);
    expect(receivedRequests).toHaveLength(1);
  });
});
